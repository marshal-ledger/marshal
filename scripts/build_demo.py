"""Build the demo ledger from the golden fixture cache, or regenerate its source list.

    python scripts/build_demo.py [demo.sqlite]     # same as `marshal demo`, reusing tests/fixtures/.cache
    python scripts/build_demo.py --update-sources  # rewrite demo-sources.json from tests/fixtures/sources.json

The demo's agents are listed in DEMO below. ``--update-sources`` copies their
repositories, commits and files from the golden fixtures into the package, so
re-pinning a fixture updates the demo too.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

from marshal_ledger import demo

ROOT = Path(__file__).resolve().parent.parent
FIXTURES = ROOT / "tests" / "fixtures" / "sources.json"
CACHE = ROOT / "tests" / "fixtures" / ".cache"
PACKAGED = ROOT / "src" / "marshal_ledger" / "demo-sources.json"

# (path in the fixture cache, deployment target)
DEMO = [
    ("databricks/agent-openai-agents-sdk", "prod"),
    ("databricks/agent-langgraph", "prod"),
    ("databricks/genie-space-nyc-taxi", None),
    ("cloudformation/bedrock-agents", None),
    ("cloudformation/agentcore", None),
    ("copilot-studio/all-the-things", None),
    ("copilot-studio/mcp-agent", None),
    ("copilot-studio/solution-leave-management", None),
    ("agentforce/agent-script/order-service.agent", None),
    ("salesforce-metadata/coral-cloud", None),
    ("python/google-adk", None),
    ("adk-config/samples/multi_agent", None),
    ("adl/examples/packages", None),
    ("terraform/acwwat-basic", None),
]


def demo_sources() -> dict:
    """The packaged source list, derived from the golden fixtures."""
    fixtures = json.loads(FIXTURES.read_text())["fixtures"]
    entries = []
    for path, target in DEMO:
        [fixture] = [f for f in fixtures if path == f["id"] or path.startswith(f["id"] + "/")]
        read = path[len(fixture["id"]) + 1:]
        files = [name for name in fixture["files"] if not read or name == read or name.startswith(read + "/")]
        entry = {"fixture": fixture["id"]} | ({"read": read} if read else {}) | ({"target": target} if target else {})
        entries.append(entry | {"repo": fixture["repo"], "commit": fixture["commit"], "root": fixture["root"], "files": files})
    return {"_comment": "Generated by scripts/build_demo.py --update-sources from tests/fixtures/sources.json.",
            "sources": entries}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("target", nargs="?", default="demo.sqlite")
    parser.add_argument("--update-sources", action="store_true", help="rewrite the packaged demo-sources.json")
    args = parser.parse_args()
    if args.update_sources:
        PACKAGED.write_text(json.dumps(demo_sources(), indent=2) + "\n")
        print(f"wrote {PACKAGED.relative_to(ROOT)}")
        return 0
    if not CACHE.exists():
        subprocess.run([sys.executable, str(ROOT / "scripts" / "fetch_fixtures.py")], check=True)
    count = demo.build(Path(args.target), CACHE)
    print(f"\nDemo ledger: {args.target} ({count} agents)\nBrowse it:   marshal web --db {args.target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
